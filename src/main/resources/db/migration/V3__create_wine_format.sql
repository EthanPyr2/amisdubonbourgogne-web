-- Un même vin peut être vendu en plusieurs formats (37,5 cl, 75 cl, magnum…), chacun avec son prix.

CREATE TABLE wine_format
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wine_id   BIGINT        NOT NULL REFERENCES wine (id) ON DELETE CASCADE,
    volume_cl NUMERIC(5, 1) NOT NULL CHECK (volume_cl > 0),
    price     NUMERIC(8, 2) NOT NULL CHECK (price > 0),
    CONSTRAINT uk_wine_format_volume UNIQUE (wine_id, volume_cl)
);

CREATE INDEX idx_wine_format_wine_id ON wine_format (wine_id);

-- Reprise des vins existants : leur prix devient un format (75 cl si le volume n'était pas renseigné)
INSERT INTO wine_format (wine_id, volume_cl, price)
SELECT id, COALESCE(volume_cl, 75), price
FROM wine;

ALTER TABLE wine
    DROP COLUMN volume_cl,
    DROP COLUMN price;
