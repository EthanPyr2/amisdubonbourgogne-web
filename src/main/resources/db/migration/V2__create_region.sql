-- Les régions deviennent des données gérées par le caviste (auparavant enum Java Region).

CREATE TABLE region
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(80)  NOT NULL UNIQUE,
    slug          VARCHAR(100) NOT NULL UNIQUE,
    display_order INTEGER      NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Régions par défaut (ordre de la carte, par pas de 10 pour pouvoir intercaler)
INSERT INTO region (name, slug, display_order)
VALUES ('Bourgogne', 'bourgogne', 10),
       ('Beaujolais', 'beaujolais', 20),
       ('Vallée du Rhône Nord', 'vallee-du-rhone-nord', 30),
       ('Vallée du Rhône Sud', 'vallee-du-rhone-sud', 40),
       ('Champagne', 'champagne', 50),
       ('Loire', 'loire', 60),
       ('Languedoc-Roussillon', 'languedoc-roussillon', 70),
       ('Bordeaux', 'bordeaux', 80),
       ('Vin de pays', 'vin-de-pays', 90),
       ('Jura', 'jura', 100),
       ('Alsace', 'alsace', 110),
       ('Autres', 'autres', 999);

-- Cava et Crémant ne sont plus des régions : ce sont des vins effervescents.
-- Ils sont rattachés à "Autres", à réassigner ensuite depuis l'admin si besoin.
UPDATE wine
SET color  = 'EFFERVESCENT',
    region = 'AUTRE'
WHERE region IN ('CAVA', 'CREMANT');

-- Remplacement de la colonne texte (nom de l'enum) par une clé étrangère
ALTER TABLE wine
    ADD COLUMN region_id BIGINT;

UPDATE wine w
SET region_id = r.id
FROM region r
WHERE r.slug = CASE w.region
                   WHEN 'BOURGOGNE' THEN 'bourgogne'
                   WHEN 'BEAUJOLAIS' THEN 'beaujolais'
                   WHEN 'RHONENORD' THEN 'vallee-du-rhone-nord'
                   WHEN 'RHONESUD' THEN 'vallee-du-rhone-sud'
                   WHEN 'CHAMPAGNE' THEN 'champagne'
                   WHEN 'LOIRE' THEN 'loire'
                   WHEN 'LGDCROUSSILLON' THEN 'languedoc-roussillon'
                   WHEN 'BORDEAUX' THEN 'bordeaux'
                   WHEN 'PAYS' THEN 'vin-de-pays'
                   WHEN 'JURA' THEN 'jura'
                   WHEN 'ALSACE' THEN 'alsace'
                   ELSE 'autres'
    END;

ALTER TABLE wine
    ALTER COLUMN region_id SET NOT NULL,
    ADD CONSTRAINT fk_wine_region FOREIGN KEY (region_id) REFERENCES region (id),
    DROP COLUMN region;

CREATE INDEX idx_wine_region_id ON wine (region_id);
